List<TopicSeed> topicSeedsForCategory(String categoryId) =>
    List<TopicSeed>.unmodifiable(
      topicSeeds.where((seed) => seed.categoryId == categoryId),
    );

List<TopicSeed> _seeds(String categoryId, List<_Seed> entries) => entries
    .map(
      (entry) => TopicSeed(
        id: 'seed.$categoryId.${entry.slug}',
        categoryId: categoryId,
        theme: entry.theme,
        conversationPatterns: <String>[entry.question1, entry.question2],
        hintCandidates: <String>[entry.hint1, entry.hint2],
      ),
    )
    .toList(growable: false);

class _Seed {
  const _Seed(
    this.slug,
    this.theme,
    this.question1,
    this.question2,
    this.hint1,
    this.hint2,
  );
  final String slug;
  final String theme;
  final String question1;
  final String question2;
  final String hint1;
  final String hint2;
}
